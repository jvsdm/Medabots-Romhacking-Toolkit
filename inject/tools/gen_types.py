"""Builds inject/include/mtbe_types.h from re/types/medabots_simon_types.tsv (Simon's Ghidra types, Rokusho E).

Enums keep their stored size (typedef u8/u16) with the values as constants Type_Name; structs are packed with explicit
padding so every field lands at its Ghidra offset, checked by _Static_assert. Unknown field types become byte arrays.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TSV = ROOT / "re/types/medabots_simon_types.tsv"
OUT = ROOT / "inject/include/mtbe_types.h"
BASE = {"byte": ("u8", 1), "char": ("s8", 1), "ushort": ("u16", 2), "short": ("s16", 2), "word": ("u16", 2),
        "uint": ("u32", 4), "int": ("s32", 4), "dword": ("u32", 4), "undefined": ("u8", 1), "undefined1": ("u8", 1),
        "undefined2": ("u16", 2), "undefined4": ("u32", 4), "bool": ("u8", 1), "pointer": ("void *", 4)}
C_KEYWORDS = {"null", "int", "char", "short", "long", "unsigned", "signed", "void", "default", "case", "switch", "struct",
              "union", "enum", "static", "const", "for", "while", "do", "if", "else", "return", "register"}


def ident(name):
    name = re.sub(r"[^A-Za-z0-9_]", "_", name or "")
    if not name or name[0].isdigit():
        name = "_" + name
    return name + "_" if name in C_KEYWORDS else name


types, fields, enums = {}, {}, {}
for line in TSV.read_text(encoding="utf-8").splitlines():
    cols = line.split("\t")
    if cols[0] == "type":
        types[cols[2]] = (cols[3], int(cols[4]))
    elif cols[0] == "field":
        fields.setdefault(cols[1], []).append((int(cols[2], 16), cols[3], cols[4], cols[5] if len(cols) > 5 else ""))
    elif cols[0] == "enumval":
        enums.setdefault(cols[1], []).append((cols[2], int(cols[3])))

out = ["/* Generated by inject/tools/gen_types.py from Simon's (STulling) Ghidra types for Rokusho (E). */",
       "/* Layouts are the same in Metabee (E) as far as checked; treat field meanings as provisional. */",
       "#pragma once", '#include "gba_types.h"', ""]
for name, (kind, size) in sorted(types.items()):
    if kind.startswith("Enum"):
        base = {1: "u8", 2: "u16"}.get(size, "u32")
        out.append(f"typedef {base} {ident(name)};")
        for value_name, value in enums.get(name, []):
            out.append(f"#define {ident(name)}_{ident(value_name)} {value}")
        out.append("")

done, emitted = set(), []
ALIGN = {"u8": 1, "s8": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "void *": 4}
struct_align = {}


def align_of(c_name):
    return ALIGN.get(c_name, struct_align.get(c_name, 1))


def c_type(type_name):
    m = re.fullmatch(r"([A-Za-z_][A-Za-z0-9_]*)((?:\[\d+\])*)", type_name.replace(" ", ""))
    if not m:
        return None
    base, dims = m.group(1), m.group(2)
    if base in BASE:
        return BASE[base][0], dims
    if base in types:
        return ident(base), dims
    return None


def emit(name):
    if name in done or name not in types or types[name][0].startswith("Enum"):
        return
    done.add(name)
    kind, size = types[name]
    members = sorted(fields.get(name, []))
    for _, _, ftype, _ in members:
        dep = re.match(r"[A-Za-z_][A-Za-z0-9_]*", ftype)
        if dep and dep.group(0) in types:
            emit(dep.group(0))
    lines = [f"typedef {'union' if 'Union' in kind else 'struct'} {ident(name)} {{"]
    cursor, used = 0, set()
    packed, max_align = False, 1
    for index, (offset, fname, ftype, comment) in enumerate(members):
        if offset > cursor:
            lines.append(f"    u8 pad_{cursor:02X}[0x{offset - cursor:X}];")
        end = members[index + 1][0] if index + 1 < len(members) else size
        fname = ident(fname)
        if fname in used:
            fname = f"{fname}_{offset:02X}"
        used.add(fname)
        mapped = c_type(ftype)
        note = f"  /* +0x{offset:02X} {comment} */" if comment else f"  /* +0x{offset:02X} */"
        if mapped:
            a = align_of(mapped[0])
            max_align = max(max_align, a)
            packed |= offset % a != 0
            lines.append(f"    {mapped[0]} {fname}{mapped[1]};{note}")
            count = 1
            for dim in re.findall(r"\[(\d+)\]", mapped[1]):
                count *= int(dim)
            base = re.match(r"[A-Za-z_][A-Za-z0-9_]*", ftype.replace(" ", "")).group(0)
            unit = BASE[base][1] if base in BASE else types[base][1]
            end = offset + unit * count
        else:
            lines.append(f"    u8 {fname}[0x{end - offset:X}];{note} /* {ftype} */")
        cursor = end
    if cursor < size:
        lines.append(f"    u8 pad_{cursor:02X}[0x{size - cursor:X}];")
    packed = True   # Ghidra layouts are packed (fields at any offset); keep them byte-exact
    if packed:
        max_align = 1
    struct_align[ident(name)] = max_align
    lines.append(f"}}{' __attribute__((packed))' if packed else ''} {ident(name)};")
    lines.append(f"_Static_assert(sizeof({ident(name)}) == 0x{size:X}, \"{name}\");")
    lines.append("")
    emitted.extend(lines)


for name in sorted(types):
    emit(name)
out.extend(emitted)
OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{OUT}: {sum(1 for t in types.values() if t[0].startswith('Enum'))} enums, {len(done)} structs")
