"""Builds the linker symbol file from re/symbols/mtbe.csv, so injected C calls game functions and uses game
data by name. Thumb functions get bit 0 set (calls interwork); everything else is its plain address."""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main(out_path):
    rows = list(csv.DictReader(open(ROOT / "re/symbols/mtbe.csv", encoding="utf-8")))
    lines = ["/* Generated by inject/tools/gen_symbols.py from re/symbols/mtbe.csv. Do not edit. */"]
    for row in rows:
        name = row["name"]
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            continue
        address = int(row["address"], 16)
        if row["kind"] == "func_thumb":
            address |= 1
        lines.append(f"{name} = 0x{address:08X};")
    Path(out_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(lines) - 1


if __name__ == "__main__":
    print(f"{main(sys.argv[1])} symbols")
